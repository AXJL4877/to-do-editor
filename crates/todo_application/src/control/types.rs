use crate::{AppUpdate, Project};
use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use todo_core::{Clip, ClipAudio, DomainError, MotionRef, TextContent, TrackKind, Transform};

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ControlRequest {
    pub request_id: String,
    pub session_id: u64,
    pub expected_revision: Option<u64>,
    pub command: ControlCommand,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(
    tag = "type",
    rename_all = "snake_case",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum ControlCommand {
    GetContext,
    /// Element-level snapshot with derived geometry, optionally evaluated at
    /// `at` seconds (entrance curves and on-screen visibility included).
    Describe {
        #[serde(default)]
        at: Option<f64>,
    },
    GetImportJob {
        job_id: u64,
    },
    ImportMedia {
        paths: Vec<PathBuf>,
        /// Virtual library folder; omit or null for root.
        #[serde(default)]
        folder_id: Option<String>,
    },
    ApplyEdits {
        edits: Vec<ControlEdit>,
        #[serde(default)]
        dry_run: bool,
    },
    Undo,
    Redo,
}

impl ControlCommand {
    pub(crate) fn is_mutation(&self) -> bool {
        !matches!(self, Self::GetContext | Self::GetImportJob { .. })
    }
}

/// Absolute source times in seconds, at normal speed. Image holds start at zero.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SourceRange {
    pub source_in: f64,
    pub source_out: f64,
}

/// `Created` resolves all clips generated by an earlier zero-based batch step.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
pub enum ClipRef {
    Id { id: String },
    Created { step: usize },
}

#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ClipEdge {
    In,
    Out,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(
    tag = "type",
    rename_all = "snake_case",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum ControlEdit {
    PlaceMedia {
        media_id: String,
        track_id: Option<String>,
        timeline_start: f64,
        source_range: Option<SourceRange>,
    },
    MoveClips {
        clips: Vec<ClipRef>,
        delta: f64,
        track_id: Option<String>,
        linked: bool,
    },
    TrimClip {
        clip: ClipRef,
        edge: ClipEdge,
        timeline_time: f64,
        linked: bool,
    },
    /// Always splits linked partners; manual `EditCommand::Split` remains explicit.
    Split {
        clips: Vec<ClipRef>,
        timeline_time: f64,
    },
    DeleteClips {
        clips: Vec<ClipRef>,
        ripple: bool,
        linked: bool,
    },
    AddTrack {
        kind: TrackKind,
    },
    SetTransform {
        clip: ClipRef,
        #[serde(deserialize_with = "super::transform::deserialize")]
        transform: Transform,
    },
    /// Styled text on a text lane (one is created when none is free). The style
    /// may be built-in; it is copied into the project on first use.
    AddText {
        track_id: Option<String>,
        timeline_start: f64,
        duration: f64,
        content: TextContent,
        /// Optional placement applied atomically after the text clip is made.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        transform: Option<Transform>,
    },
    /// Replace a text clip's content; timing and transform are kept.
    SetText {
        clip: ClipRef,
        content: TextContent,
    },
    CreateFolder {
        id: String,
        name: String,
        parent_id: Option<String>,
    },
    RenameFolder {
        id: String,
        name: String,
    },
    DeleteFolder {
        id: String,
    },
    MoveFolder {
        id: String,
        parent_id: Option<String>,
    },
    MoveMedia {
        media_id: String,
        folder_id: Option<String>,
    },
    /// Entrance of a picture or text clip; `kind` is an intro preset id
    /// (built-in, or from the motion library), `null` removes it.
    SetIntro {
        clip: ClipRef,
        intro: Option<MotionRef>,
    },
    /// Exit of a picture or text clip (an outro preset), `null` removes it.
    SetOutro {
        clip: ClipRef,
        outro: Option<MotionRef>,
    },
    /// Transition into the clip from the clip ending where it starts on the
    /// same track (a transition preset, window centred on the cut).
    SetTransition {
        clip: ClipRef,
        transition: Option<MotionRef>,
    },
    /// Gain (0..4) and fades of an audio clip.
    SetAudio {
        clip: ClipRef,
        audio: Option<ClipAudio>,
    },
    /// Show another library item in a media clip; a picture keeps its height.
    ReplaceMedia {
        clip: ClipRef,
        media_id: String,
    },
}

impl ControlEdit {
    /// The motion preset this edit names, if any.
    pub fn motion(&self) -> Option<&MotionRef> {
        match self {
            Self::SetIntro { intro: motion, .. }
            | Self::SetOutro { outro: motion, .. }
            | Self::SetTransition {
                transition: motion, ..
            } => motion.as_ref(),
            _ => None,
        }
    }
}

