#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "status", rename_all = "snake_case")]
pub enum ControlStatus {
    Ok { result: ControlResult },
    Error { error: ControlError },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ControlResult {
    Context { context: Box<ControlContext> },
    Document { document: Box<super::ProjectView> },
    Edits { receipt: EditReceipt },
    ImportStarted { job: ImportJob },
    ImportJob { job: ImportJob },
    History { changed: bool },
}

/// Effect-bearing outcome is deliberately separate from the serializable reply.
#[derive(Debug, Clone)]
pub struct ControlOutcome {
    pub response: ControlResponse,
    pub update: AppUpdate,
}

