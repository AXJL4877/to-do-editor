#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ControlError {
    pub code: String,
    pub message: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub object_id: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub step: Option<usize>,
}

impl ControlError {
    pub(crate) fn new(code: &str, message: &str) -> Self {
        Self {
            code: code.into(),
            message: message.into(),
            object_id: None,
            step: None,
        }
    }
    pub(crate) fn domain(error: DomainError) -> Self {
        let object_id = match &error {
            DomainError::MediaNotFound(id)
            | DomainError::TrackNotFound(id)
            | DomainError::ClipNotFound(id)
            | DomainError::TrackLocked(id)
            | DomainError::IncompatibleTrack(id)
            | DomainError::Overlap(id)
            | DomainError::SourceBounds(id)
            | DomainError::ClipTooShort(id)
            | DomainError::DuplicateId(id)
            | DomainError::MediaInUse(id) => Some(id.clone()),
            _ => None,
        };
        Self {
            code: error.message_key().into(),
            message: format!("Edit rejected: {error}"),
            object_id,
            step: None,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ImportStatus {
    Running,
    Completed,
    CompletedWithErrors,
    Failed,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ImportJob {
    pub job_id: u64,
    pub session_id: u64,
    pub status: ImportStatus,
    pub total: usize,
    pub completed: usize,
    pub media_ids: Vec<String>,
    pub errors: Vec<String>,
}
